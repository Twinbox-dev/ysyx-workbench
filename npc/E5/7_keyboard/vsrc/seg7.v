// =============================================================================
// 十六进制数字 -> 七段数码管段码
//
// 输出位序与 nvboard 的引脚绑定顺序一致：
//   seg[7]=A seg[6]=B seg[5]=C seg[4]=D seg[3]=E seg[2]=F seg[1]=G seg[0]=DP
// 全部低电平有效（0 = 点亮），因此 DP 恒为 1（不亮）。
//
// blank = 1 时整个数码管熄灭（8'hFF）。
// =============================================================================

module seg7_hex (
    input  wire [3:0] hex,
    input  wire       blank,
    output wire [7:0] seg
);

    // 段码按 {A,B,C,D,E,F,G} 排列，1 = 该段点亮
    wire [6:0] pattern;

    MuxKeyWithDefault #(16, 4, 7) dec (
        .out(pattern),
        .key(hex),
        .default_out(7'b0000000),
        .lut({
            4'h0, 7'b1111110,
            4'h1, 7'b0110000,
            4'h2, 7'b1101101,
            4'h3, 7'b1111001,
            4'h4, 7'b0110011,
            4'h5, 7'b1011011,
            4'h6, 7'b1011111,
            4'h7, 7'b1110000,
            4'h8, 7'b1111111,
            4'h9, 7'b1111011,
            4'hA, 7'b1110111,
            4'hB, 7'b0011111,
            4'hC, 7'b1001110,
            4'hD, 7'b0111101,
            4'hE, 7'b1001111,
            4'hF, 7'b1000111
        })
    );

    // 取反转成低有效，最低位是小数点（恒不亮）
    assign seg = blank ? 8'hFF : {~pattern, 1'b1};

endmodule
